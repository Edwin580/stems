// Compiles assembly/fft.ts (AssemblyScript, SIMD) and embeds the binary as
// base64 in src/engine/wasm-fft-bin.ts so workers can load it synchronously.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const out = join(mkdtempSync(join(tmpdir(), 'stems-wasm-')), 'fft.wasm');
execFileSync('npx', ['asc', 'assembly/fft.ts', '--enable', 'simd', '-O3', '--runtime', 'stub', '--noAssert', '--outFile', out], { stdio: 'inherit' });
const b64 = readFileSync(out).toString('base64');
writeFileSync('src/engine/wasm-fft-bin.ts', `// Generated by scripts/build-wasm.mjs from assembly/fft.ts. Do not edit.\nexport const FFT_WASM_BASE64 = '${b64}';\n`);
console.log(`wrote src/engine/wasm-fft-bin.ts (${b64.length} chars)`);
